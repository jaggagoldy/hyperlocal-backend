#!/usr/bin/env node
/**
 * P0 · Performance Baseline capture (exit criterion E6).
 *
 * Hits core PUBLIC read paths against a RUNNING server, N times each, and
 * computes p50/p95/p99 latency. Writes a machine-readable JSON and a
 * human-readable Markdown artifact under releases/P0/.
 *
 * SAFETY: point this at a LOCAL server only (never production Neon). It sends
 * only idempotent GET requests to public endpoints, but latency runs create
 * load — do not run against prod.
 *
 * Usage:
 *   BASE_URL=http://localhost:3000 N=50 node scripts/perf-baseline.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const BASE = process.env.BASE_URL || 'http://localhost:3000';
const N = Number(process.env.N || 50);
const WARMUP = Number(process.env.WARMUP || 5);

// Core read paths. All public GET. Some hit the DB, some are static/config —
// the mix is intentional so the baseline reflects real middleware + query cost.
const ENDPOINTS = [
  { name: 'root',        path: '/' },
  { name: 'health',      path: '/health' },
  { name: 'ping',        path: '/api/v1/ping' },
  { name: 'meta',        path: '/api/v1/meta' },
  { name: 'releases',    path: '/api/v1/releases' },
  { name: 'verticals',   path: '/api/v1/verticals' },
  { name: 'categories',  path: '/api/v1/categories' },
  { name: 'regions',     path: '/api/v1/regions' },
  { name: 'autocomplete', path: '/api/v1/search/autocomplete?q=clinic' },
];

const pct = (sorted, p) => {
  if (!sorted.length) return null;
  const idx = Math.min(sorted.length - 1, Math.ceil((p / 100) * sorted.length) - 1);
  return sorted[idx];
};
const round = (n) => (n == null ? null : Math.round(n * 100) / 100);

async function timeOnce(url) {
  const t0 = performance.now();
  let status = 0;
  try {
    const res = await fetch(url);
    status = res.status;
    await res.text(); // drain body so timing includes full response
  } catch {
    status = -1;
  }
  return { ms: performance.now() - t0, status };
}

async function measure(ep) {
  const url = BASE + ep.path;
  for (let i = 0; i < WARMUP; i++) await timeOnce(url); // warmup (not recorded)
  const samples = [];
  let lastStatus = 0;
  for (let i = 0; i < N; i++) {
    const { ms, status } = await timeOnce(url);
    samples.push(ms);
    lastStatus = status;
  }
  const sorted = [...samples].sort((a, b) => a - b);
  return {
    name: ep.name,
    path: ep.path,
    status: lastStatus,
    n: N,
    min: round(sorted[0]),
    p50: round(pct(sorted, 50)),
    p95: round(pct(sorted, 95)),
    p99: round(pct(sorted, 99)),
    max: round(sorted[sorted.length - 1]),
    avg: round(samples.reduce((a, b) => a + b, 0) / samples.length),
  };
}

async function main() {
  const __dirname = path.dirname(fileURLToPath(import.meta.url));
  const outDir = path.resolve(__dirname, '../releases/P0');

  console.log(`Perf baseline → ${BASE}  (N=${N}, warmup=${WARMUP})\n`);
  const results = [];
  for (const ep of ENDPOINTS) {
    const r = await measure(ep);
    results.push(r);
    console.log(
      `${r.name.padEnd(11)} [${String(r.status).padStart(3)}]  p50=${String(r.p50).padStart(7)}ms  p95=${String(r.p95).padStart(7)}ms  p99=${String(r.p99).padStart(7)}ms`
    );
  }

  const captured = new Date().toISOString();
  const meta = { capturedAt: captured, base: BASE, n: N, warmup: WARMUP, node: process.version };
  fs.writeFileSync(path.join(outDir, 'perf-baseline.json'), JSON.stringify({ meta, results }, null, 2) + '\n');

  const md = [
    '# P0 · Performance Baseline (E6)',
    '',
    '> Auto-generated by `scripts/perf-baseline.js`. Captures p50/p95/p99 on core public read paths.',
    '> **Local baseline** — measured against a local server + local `hyperlocal_dev` DB, never production.',
    '',
    `- **Captured:** ${captured}`,
    `- **Target:** \`${BASE}\``,
    `- **Samples per endpoint:** ${N} (after ${WARMUP} warmup)`,
    `- **Runtime:** Node ${process.version}`,
    '',
    '| Endpoint | Path | HTTP | p50 (ms) | p95 (ms) | p99 (ms) | min | max | avg |',
    '|---|---|---|---|---|---|---|---|---|',
    ...results.map(
      (r) => `| ${r.name} | \`${r.path}\` | ${r.status} | ${r.p50} | **${r.p95}** | ${r.p99} | ${r.min} | ${r.max} | ${r.avg} |`
    ),
    '',
    '## How to reproduce',
    '',
    '```bash',
    '# boot against LOCAL db only',
    'DATABASE_URL=postgresql://<local> JWT_SECRET=<any> node src/server.js &',
    'BASE_URL=http://localhost:3000 N=50 node scripts/perf-baseline.js',
    '```',
    '',
    '## Interpretation',
    '',
    'This is the **regression tripwire** for P0 and later phases: if a future change',
    'pushes p95 on these paths materially above this baseline, that is a signal to',
    'investigate before shipping. A production baseline (against Render + Neon) should',
    'be captured separately once the deploy gate (E1/E8) is live; it will be higher',
    'due to network + managed-DB latency, and becomes the prod tripwire.',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, 'perf-baseline.md'), md);
  console.log(`\nWrote releases/P0/perf-baseline.json and perf-baseline.md`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
